//! Runtime view of the effect data (roadmap 1.5, Appendix A.3).
//!
//! Holds the `EffectDef`s (hand-written files, the champion point stars' effects and the reviewed rows of
//! the compiler's `effects.jsonl`, which is where the mundus stones live), the champion point stars and
//! which skill line each ability is in.
//! Everything is compiled in with `include_str!`, so it works in WASM with no file IO.

use std::collections::{BTreeMap, HashMap};
use std::sync::OnceLock;

use eso_skill_data::enums::skill_line::SkillLine;
use esosim_types::{CpStar, EffectDef};

#[derive(Default, Debug)]
pub struct Bundle {
    pub effects: HashMap<u32, EffectDef>,
    /// The champion point table, by star id (`cp.jsonl`).
    pub stars: BTreeMap<u32, CpStar>,
    /// The skill line of each ability that has one (`skill_lines.csv`).
    skill_lines: HashMap<u32, SkillLine>,
    abilities_by_line: HashMap<SkillLine, Vec<u32>>,
    /// Every passive that has ranks: ability id -> (the row's first id, its rank counted from 0) (`passive_ranks.csv`).
    passive_ranks: HashMap<u32, (u32, usize)>,
    /// Skill line ids in `skill_lines.csv` that `eso_skill_data` has no `SkillLine` for; their
    /// abilities are not indexed. Empty when the data and the parser are from the same patch.
    pub unknown_skill_lines: Vec<u32>,
}

impl Bundle {
    /// All effect files compiled into the binary.
    pub fn embedded() -> &'static Bundle {
        static EMBEDDED: OnceLock<Bundle> = OnceLock::new();
        EMBEDDED.get_or_init(|| {
            let mut bundle = Bundle::default();
            // generated by the data compiler (roadmap 2.2c); an id also written in the files above is an error
            bundle
                .add_jsonl(esosim_data::CP_EFFECTS_JSONL)
                .unwrap_or_else(|e| panic!("embedded effect file cp_effects.jsonl: {e}"));
            // the rows a person wrote in the compiler's overrides.toml (roadmap 2.3: the mundus stones); the
            // auto-classified rows of the same file have unchecked units and stay out
            bundle
                .add_reviewed_jsonl(esosim_data::EFFECTS_JSONL)
                .unwrap_or_else(|e| panic!("embedded effect file effects.jsonl: {e}"));
            bundle.add_stars_jsonl(esosim_data::CP_JSONL).unwrap_or_else(|e| panic!("embedded cp.jsonl: {e}"));
            bundle
                .add_skill_lines_csv(esosim_data::SKILL_LINES_CSV)
                .unwrap_or_else(|e| panic!("embedded skill_lines.csv: {e}"));
            bundle
                .add_passive_ranks_csv(esosim_data::PASSIVE_RANKS_CSV)
                .unwrap_or_else(|e| panic!("embedded passive_ranks.csv: {e}"));
            bundle
        })
    }

    /// One `EffectDef` per line; blank lines and lines starting with `//` are skipped.
    /// A duplicate id is an error.
    pub fn from_jsonl(effects: &str) -> Result<Self, String> {
        let mut bundle = Bundle::default();
        bundle.add_jsonl(effects)?;
        Ok(bundle)
    }

    pub fn add_jsonl(&mut self, effects: &str) -> Result<(), String> {
        for (i, line) in effects.lines().enumerate() {
            let line = line.trim();
            if line.is_empty() || line.starts_with("//") {
                continue;
            }
            let def: EffectDef =
                serde_json::from_str(line).map_err(|e| format!("effects line {}: {e}", i + 1))?;
            self.insert_def(i, def)?;
        }
        Ok(())
    }

    /// The rows of the compiler's `effects.jsonl` that a person wrote (`"provenance":"override"`, from
    /// `overrides.toml`). Rows with `"provenance":"auto"` are skipped: their units are not checked
    /// against the engine's channels (see the compiler's `effects.rs`). A duplicate id is an error.
    pub fn add_reviewed_jsonl(&mut self, effects: &str) -> Result<(), String> {
        for (i, line) in effects.lines().enumerate() {
            let line = line.trim();
            if line.is_empty() || line.starts_with("//") {
                continue;
            }
            let row: serde_json::Value =
                serde_json::from_str(line).map_err(|e| format!("effects line {}: {e}", i + 1))?;
            if row.get("provenance").and_then(|p| p.as_str()) != Some("override") {
                continue;
            }
            let def: EffectDef =
                serde_json::from_value(row).map_err(|e| format!("effects line {}: {e}", i + 1))?;
            self.insert_def(i, def)?;
        }
        Ok(())
    }

    fn insert_def(&mut self, line_index: usize, def: EffectDef) -> Result<(), String> {
        let id = def.id;
        match self.effects.insert(id, def) {
            Some(prev) => Err(format!("effects line {}: duplicate id {id} (`{}`)", line_index + 1, prev.name)),
            None => Ok(()),
        }
    }

    /// One `CpStar` per line. A repeated star id is an error.
    pub fn add_stars_jsonl(&mut self, stars: &str) -> Result<(), String> {
        for (i, line) in stars.lines().enumerate() {
            let line = line.trim();
            if line.is_empty() {
                continue;
            }
            let star: CpStar = serde_json::from_str(line).map_err(|e| format!("stars line {}: {e}", i + 1))?;
            let id = star.id;
            if self.stars.insert(id, star).is_some() {
                return Err(format!("stars line {}: duplicate star id {id}", i + 1));
            }
        }
        Ok(())
    }

    /// `skill line id,ability id,...` per line, as the compiler writes `skill_lines.csv`. An ability
    /// in two lines is an error.
    pub fn add_skill_lines_csv(&mut self, csv: &str) -> Result<(), String> {
        for (n, row) in csv.lines().enumerate().filter(|(_, l)| !l.trim().is_empty()) {
            let mut cells = row.trim().split(',');
            let line_cell = cells.next().unwrap_or("");
            let line_id: u32 =
                line_cell.parse().map_err(|_| format!("skill lines line {}: bad skill line id {line_cell:?}", n + 1))?;
            let line = SkillLine::from_id(&line_id);
            if line.is_none() {
                self.unknown_skill_lines.push(line_id);
            }
            for cell in cells {
                let id: u32 = cell.parse().map_err(|_| format!("skill lines line {}: bad ability id {cell:?}", n + 1))?;
                let Some(line) = line else { continue };
                if self.skill_lines.insert(id, line).is_some() {
                    return Err(format!("skill lines line {}: ability {id} is in two skill lines", n + 1));
                }
                self.abilities_by_line.entry(line).or_default().push(id);
            }
        }
        Ok(())
    }

    /// `ability id,ability id,...` per line, the ranks of one passive, lowest first, as `passive_ranks.csv`. An ability
    /// in two rows is an error.
    pub fn add_passive_ranks_csv(&mut self, csv: &str) -> Result<(), String> {
        for (n, row) in csv.lines().enumerate().filter(|(_, l)| !l.trim().is_empty()) {
            let mut first = None;
            for (rank, cell) in row.trim().split(',').enumerate() {
                let id: u32 = cell.trim().parse().map_err(|_| format!("passive ranks line {}: bad ability id {cell:?}", n + 1))?;
                let line = *first.get_or_insert(id);
                if self.passive_ranks.insert(id, (line, rank)).is_some() {
                    return Err(format!("passive ranks line {}: ability {id} is in two rows", n + 1));
                }
            }
        }
        Ok(())
    }

    /// `ids` with, for every passive that has ranks, only the highest rank listed: a character holds one rank of a
    /// passive, and the ranks are alternatives (each has its own effects), so listing two must not count both.
    /// Ids that are not ranks of a passive, and the order, are kept.
    pub fn highest_ranks(&self, ids: &[u32]) -> Vec<u32> {
        let mut best: HashMap<u32, (usize, u32)> = HashMap::new();
        for id in ids {
            if let Some(&(line, rank)) = self.passive_ranks.get(id) {
                let held = best.entry(line).or_insert((rank, *id));
                if rank > held.0 {
                    *held = (rank, *id);
                }
            }
        }
        ids.iter()
            .copied()
            .filter(|id| match self.passive_ranks.get(id) {
                Some((line, _)) => best[line].1 == *id,
                None => true,
            })
            .collect()
    }

    /// The skill line an ability belongs to (`None`: it is in no line, or in one the parser does not know).
    pub fn skill_line_of(&self, ability_id: u32) -> Option<SkillLine> {
        self.skill_lines.get(&ability_id).copied()
    }

    /// Every ability of `line`, in id order.
    pub fn abilities_in_skill_line(&self, line: &SkillLine) -> &[u32] {
        self.abilities_by_line.get(line).map(Vec::as_slice).unwrap_or(&[])
    }

    pub fn effect(&self, id: u32) -> Option<&EffectDef> {
        self.effects.get(&id)
    }

    /// Ids that a condition refers to (`SelfBuffActive`, `TargetDebuffActive`) but that have
    /// no effect in the bundle. Sorted and de-duplicated.
    pub fn dangling_ids(&self) -> Vec<u32> {
        let mut referenced = Vec::new();
        for def in self.effects.values() {
            def.condition.referenced_effect_ids(&mut referenced);
        }
        referenced.retain(|id| !self.effects.contains_key(id));
        referenced.sort_unstable();
        referenced.dedup();
        referenced
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn embedded_data_loads_and_has_no_dangling_ids() {
        let b = Bundle::embedded();
        assert!(b.effect(142035).is_some());
        assert!(b.dangling_ids().is_empty());
    }

    #[test]
    fn only_the_highest_listed_rank_of_a_passive_is_kept() {
        let mut b = Bundle::default();
        b.add_passive_ranks_csv("10,11,12\n20,21\n").unwrap();
        assert_eq!(b.highest_ranks(&[11, 10]), vec![11]);
        assert_eq!(b.highest_ranks(&[10, 12, 11, 99, 20]), vec![12, 99, 20]);
        assert_eq!(b.highest_ranks(&[21, 20, 12]), vec![21, 12]);
        assert_eq!(b.highest_ranks(&[]), Vec::<u32>::new());
        assert!(b.add_passive_ranks_csv("12,30\n").is_err(), "12 is already a rank of another row");
    }

    /// Roadmap 2.4: every rank of a passive that has several is an `ability_id` of some passive effect, so a build that
    /// holds any rank gets that rank's numbers, and every rank-row passive has its effects at every rank.
    #[test]
    fn every_rank_in_passive_ranks_has_effects() {
        use esosim_types::EffectSource;
        let b = Bundle::embedded();
        let with_effects: std::collections::HashSet<u32> = b
            .effects
            .values()
            .filter_map(|d| match d.source {
                EffectSource::Race { ability_id, .. } | EffectSource::Class { ability_id, .. } | EffectSource::Passive { ability_id } => Some(ability_id),
                _ => None,
            })
            .collect();
        let rows: Vec<Vec<u32>> = esosim_data::PASSIVE_RANKS_CSV
            .lines()
            .filter(|l| !l.trim().is_empty())
            .map(|l| l.split(',').map(|c| c.trim().parse().unwrap()).collect())
            .collect();
        assert!(rows.len() > 80, "{}", rows.len());
        for row in rows {
            for id in &row {
                assert!(with_effects.contains(id), "rank {id} of {row:?} has no effect");
            }
        }
    }

    #[test]
    fn only_reviewed_rows_of_effects_jsonl_are_loaded() {
        let row = |id: u32, provenance: &str| {
            format!(
                r#"{{"id":{id},"name":"E{id}","source":"Food","channels":[{{"channel":"CriticalChance","value":1.0,"value_per_stack":0.0}}],"condition":"Always","stacking":"Unique","provenance":"{provenance}"}}"#
            )
        };
        let mut b = Bundle::default();
        b.add_reviewed_jsonl(&format!("{}\n{}\n", row(1, "override"), row(2, "auto"))).unwrap();
        assert_eq!(b.effects.keys().copied().collect::<Vec<_>>(), [1]);
        // an override that repeats an id of the hand-written files is an error, not a double count
        let err = b.add_reviewed_jsonl(&row(1, "override")).unwrap_err();
        assert!(err.contains("duplicate id 1"), "{err}");
    }

    #[test]
    fn embedded_skill_lines_load_and_every_line_is_known() {
        let b = Bundle::embedded();
        assert!(b.unknown_skill_lines.is_empty(), "skill lines the parser does not know: {:?}", b.unknown_skill_lines);
        // Toppling Charge (15540) is in skill line 22
        let line = b.skill_line_of(15540).expect("Toppling Charge has a skill line");
        assert_eq!(SkillLine::from_id(&22), Some(line));
        assert!(b.abilities_in_skill_line(&line).contains(&15540));
        assert_eq!(b.skill_line_of(1), None);
    }

    #[test]
    fn an_ability_in_two_skill_lines_is_an_error() {
        let mut known = (0u32..4096).filter(|id| SkillLine::from_id(id).is_some());
        let (a, b) = (known.next().unwrap(), known.next().unwrap());
        let err = Bundle::default().add_skill_lines_csv(&format!("{a},5,6\n{b},6\n")).unwrap_err();
        assert!(err.contains("ability 6 is in two skill lines"), "{err}");
        assert!(Bundle::default().add_skill_lines_csv("x,5\n").is_err());
    }

    #[test]
    fn bad_json_names_the_line() {
        let err = Bundle::from_jsonl("// comment\n{nope}\n").unwrap_err();
        assert!(err.starts_with("effects line 2:"), "{err}");
    }
}
